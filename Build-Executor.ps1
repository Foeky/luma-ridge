param(
    [string]$OutputPath = (Join-Path $PSScriptRoot 'LumaRidge.executor.luau')
)

$ErrorActionPreference = 'Stop'
$library = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'LumaRidge.luau') -Raw
$demo = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'Demo.client.luau') -Raw
$demoParts = $demo -split '\r?\n\r?\n', 2
if ($demoParts.Count -ne 2 -or $demoParts[0] -notmatch '(?m)^local LumaRidge = require\(' -or
    $demoParts[1] -notmatch '^local window = LumaRidge\.new\(\{') {
    throw 'Unexpected demo structure in Demo.client.luau.'
}
$library = $library.TrimEnd() -replace '(?m)^(?=\S|[ \t]+\S)', '    '
$demo = $demoParts[1].TrimEnd().Replace(
    'local window = LumaRidge.new({',
    "local window = LumaRidge.new({`n    name = `"LumaRidgeExecutorDemo`","
)

$source = @"
-- Generated by Build-Executor.ps1 from LumaRidge.luau and Demo.client.luau.
if not game:IsLoaded() then
    game.Loaded:Wait()
end

local players = game:GetService("Players")
while not players.LocalPlayer do
    players:GetPropertyChangedSignal("LocalPlayer"):Wait()
end

local function loadLibrary()
$library
end

local LumaRidge = loadLibrary()
local playerGui = players.LocalPlayer:WaitForChild("PlayerGui")
local previousDemo = playerGui:FindFirstChild("LumaRidgeExecutorDemo")
if previousDemo and previousDemo:IsA("ScreenGui") then
    previousDemo:Destroy()
end

$demo
"@
Set-Content -LiteralPath $OutputPath -Value (($source -replace '\r\n', "`n") + "`n") -Encoding utf8NoBOM -NoNewline
Write-Output "Built $OutputPath"
